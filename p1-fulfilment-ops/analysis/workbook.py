"""Excel workbook with the node KPIs as live formulas over exported fact sheets."""
from __future__ import annotations

from pathlib import Path

from openpyxl import Workbook
from openpyxl.formatting.rule import FormulaRule
from openpyxl.styles import Font, PatternFill

from shared.excel import INPUT_FILL, add_formula_column, autosize, col_of, style_header, write_frame

PCT, NUM1, MONEY, INT = "0.0%", "0.0", "#,##0.00", "#,##0"


def build(con, cfg: dict, out: Path) -> Path:
    wb = Workbook()
    about = wb.active
    about.title = "about"
    about.append(["Fulfilment and delivery KPIs (SIMULATED DATA: generated by a seeded Python model, not real company data)"])
    about["A1"].font = Font(bold=True, size=13)
    about.append([])
    about.append(["Parameter", "Value", "Meaning"])
    style_header(about, 3, 3)
    about.append(["sla_minutes", cfg["ops"]["sla_minutes"], "Delivery promise used when the SQL computed orders_within_sla (change it in config.toml and rebuild)"])
    about.append(["sla_target", 0.90, "Target share of orders within SLA; node_summary flags nodes below it (edit freely)"])
    about["B5"].fill = INPUT_FILL
    about["B5"].number_format = PCT
    about.append([])
    about.append(["Sheets: node_day, defects, fill and riders hold exported facts as values; node_summary computes every rate "
                  "with SUMIFS formulas over them, so the numbers recompute if the facts are filtered or edited. "
                  "P50/P90 delivery minutes are not additive and are carried as values from the SQL layer."])
    autosize(about)
    about.column_dimensions["A"].width = 16
    about.column_dimensions["C"].width = 90

    node_day = con.execute("""SELECT node_id, order_date, orders_placed, orders_cancelled, orders_timed, orders_within_sla,
                              delivery_min_sum, gmv_placed FROM kpi_delivery_node_day ORDER BY node_id, order_date""").df()
    ws = wb.create_sheet("node_day")
    write_frame(ws, node_day, {"order_date": "yyyy-mm-dd", "delivery_min_sum": NUM1, "gmv_placed": MONEY})
    n = len(node_day)
    add_formula_column(ws, "pct_within_sla", "=IFERROR(F{r}/E{r},\"\")", n, PCT)
    add_formula_column(ws, "mean_delivery_min", "=IFERROR(G{r}/E{r},\"\")", n, NUM1)

    defects = con.execute("""SELECT node_id, defect_type, delivered_orders, orders_with_defect, claims, refund_amount
                             FROM kpi_defects_node ORDER BY node_id, defect_type""").df()
    wd = wb.create_sheet("defects")
    write_frame(wd, defects, {"refund_amount": MONEY})
    add_formula_column(wd, "defect_rate", "=D{r}/C{r}", len(defects), "0.00%")

    fill = con.execute("""SELECT node_id, category, units_ordered, units_fulfilled, short_value
                          FROM kpi_fill_node_category ORDER BY node_id, category""").df()
    wf = wb.create_sheet("fill")
    write_frame(wf, fill, {"short_value": MONEY})
    add_formula_column(wf, "fill_rate", "=D{r}/C{r}", len(fill), "0.00%")

    riders = con.execute("""SELECT node_id, sum(online_min) / 60 AS rider_hours, sum(busy_min) / 60 AS busy_hours,
                            sum(orders_delivered) AS orders_delivered
                            FROM kpi_riders_node_hour GROUP BY node_id ORDER BY node_id""").df()
    wr = wb.create_sheet("riders")
    write_frame(wr, riders, {"rider_hours": NUM1, "busy_hours": NUM1})

    pct = con.execute("""SELECT node_id, p50_delivery_min, p90_delivery_min FROM kpi_delivery_node ORDER BY node_id = 'ALL', node_id""").df()
    s = wb.create_sheet("node_summary", 1)
    headers = ["node_id", "orders_placed", "orders_timed", "orders_within_sla", "pct_within_sla", "vs_target",
               "cancel_rate", "mean_delivery_min", "p50_delivery_min (value)", "p90_delivery_min (value)",
               "missing_item_rate", "wrong_item_rate", "damaged_rate", "late_claim_rate", "refund_amount",
               "fill_rate", "rider_utilisation", "orders_per_rider_hour"]
    s.append(headers)
    style_header(s, 1, len(headers))
    nd = {h: col_of(ws, h) for h in ["node_id", "orders_placed", "orders_cancelled", "orders_timed", "orders_within_sla", "delivery_min_sum"]}
    ref = lambda sheet, col: f"{sheet}!${col}:${col}"  # noqa: E731
    sumifs = lambda sheet, col, key, r: f"SUMIFS({ref(sheet, col)},{ref(sheet, 'A')},{key}{r})"  # noqa: E731
    nodes = [x for x in pct.node_id if x != "ALL"]
    for i, node in enumerate(nodes + ["ALL"], start=2):
        if node == "ALL":
            last = len(nodes) + 1
            sums = {c: f"=SUM({c}2:{c}{last})" for c in "BCD"}
            row = [node, sums["B"], sums["C"], sums["D"]]
        else:
            row = [node, f"={sumifs('node_day', nd['orders_placed'], 'A', i)}",
                   f"={sumifs('node_day', nd['orders_timed'], 'A', i)}", f"={sumifs('node_day', nd['orders_within_sla'], 'A', i)}"]
        crit = "\"*\"" if node == "ALL" else f"A{i}"
        sumifs_k = lambda sheet, col: f"SUMIFS({ref(sheet, col)},{ref(sheet, 'A')},{crit})"  # noqa: E731
        typed = lambda t: (f"=SUMIFS(defects!$D:$D,defects!$A:$A,{crit},defects!$B:$B,\"{t}\")"  # noqa: E731
                           f"/SUMIFS(defects!$C:$C,defects!$A:$A,{crit},defects!$B:$B,\"{t}\")")
        p = pct[pct.node_id == node].iloc[0]
        row += [f"=D{i}/C{i}", f"=IF(E{i}>=about!$B$5,\"meets\",\"below\")",
                f"={sumifs_k('node_day', nd['orders_cancelled'])}/B{i}",
                f"={sumifs_k('node_day', nd['delivery_min_sum'])}/C{i}",
                round(float(p.p50_delivery_min), 3), round(float(p.p90_delivery_min), 3),
                typed("missing_item"), typed("wrong_item"), typed("damaged"), typed("late"),
                f"={sumifs_k('defects', 'F')}",
                f"={sumifs_k('fill', 'D')}/{sumifs_k('fill', 'C')}",
                f"={sumifs_k('riders', 'C')}/{sumifs_k('riders', 'B')}",
                f"={sumifs_k('riders', 'D')}/{sumifs_k('riders', 'B')}"]
        s.append(row)
    fmts = {"E": PCT, "G": "0.00%", "H": NUM1, "I": NUM1, "J": NUM1, "K": "0.00%", "L": "0.00%", "M": "0.00%",
            "N": "0.00%", "O": MONEY, "P": "0.00%", "Q": PCT, "R": "0.00", "B": INT, "C": INT, "D": INT}
    for col, f in fmts.items():
        for r in range(2, len(nodes) + 3):
            s[f"{col}{r}"].number_format = f
    last = len(nodes) + 2
    s.conditional_formatting.add(f"E2:E{last}", FormulaRule(formula=["E2<about!$B$5"], fill=PatternFill("solid", fgColor="F8D7D7")))
    for c in range(1, len(headers) + 1):
        s.cell(row=last, column=c).font = Font(bold=True)
    s.freeze_panes = "B2"
    autosize(s)
    for c in "BCDEFGHIJKLMNOPQR":
        s.column_dimensions[c].width = 14
    out.parent.mkdir(exist_ok=True)
    wb.save(out)
    return out
