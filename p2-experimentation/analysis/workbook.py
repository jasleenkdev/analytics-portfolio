"""Excel workbook: test statistics, power and DiD as live formulas over exported sufficient statistics."""
from __future__ import annotations

from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.formatting.rule import FormulaRule
from openpyxl.styles import Font, PatternFill

from shared.excel import INPUT_FILL, add_formula_column, autosize, style_header, write_frame

PCT, NUM, NUM4 = "0.0%", "#,##0.000", "0.0000"


def build(con, cfg: dict, findings: dict, out: Path) -> Path:
    a = cfg["analysis"]
    wb = Workbook()
    ab = wb.active
    ab.title = "about"
    ab.append(["Experiment readout workbook (SIMULATED DATA: generated by a seeded Python model, not real company data)"])
    ab["A1"].font = Font(bold=True, size=13)
    ab.append([])
    ab.append(["Parameter", "Value", "Meaning"])
    style_header(ab, 3, 3)
    ab.append(["alpha", a["alpha"], "Two-sided significance level (edit: every CI and p-value recomputes)"])
    ab.append(["power", a["power"], "Target power for the minimum detectable effect"])
    ab.append(["z_alpha", "=NORM.S.INV(1-B4/2)", "Critical value for the CI"])
    ab.append(["z_power", "=NORM.S.INV(B5)", "Quantile for the power calculation"])
    ab.append(["srm_alpha", a["srm_alpha"], "Threshold for the sample-ratio alarm (per day, Bonferroni-corrected)"])
    for c in ("B4", "B5", "B8"):
        ab[c].fill = INPUT_FILL
    ab.append([])
    ab.append(["Sheets hold sufficient statistics (n, mean, variance) as values and compute differences, standard errors, "
                "confidence intervals, p-values, power and difference-in-differences as formulas. Normal approximation is "
                "used for the CIs; with tens of thousands of users per arm it matches the Welch t results in the README."])
    autosize(ab)
    ab.column_dimensions["C"].width = 80

    flagged = findings["promo"]["srm"]["flagged_dates"]
    arms = con.execute("""
        UNPIVOT (SELECT variant, orders, gmv, contribution, CAST(converted AS DOUBLE) AS converted, fee_revenue, product_margin
                 FROM exp_user_metrics WHERE CAST(assign_date AS VARCHAR) NOT IN (SELECT unnest(?)))
        ON orders, gmv, contribution, converted, fee_revenue, product_margin INTO NAME metric VALUE value""", [flagged]).df()
    g = arms.groupby(["metric", "variant"]).value.agg(["count", "mean", "var"]).unstack()
    tbl = pd.DataFrame({"metric": g.index, "n_control": g[("count", "control")].values, "mean_control": g[("mean", "control")].values,
                        "var_control": g[("var", "control")].values, "n_treatment": g[("count", "treatment")].values,
                        "mean_treatment": g[("mean", "treatment")].values, "var_treatment": g[("var", "treatment")].values})
    ws = wb.create_sheet("promo_arms")
    write_frame(ws, tbl, {"mean_control": NUM, "var_control": NUM, "mean_treatment": NUM, "var_treatment": NUM})
    n = len(tbl)
    add_formula_column(ws, "diff", "=F{r}-C{r}", n, NUM)
    add_formula_column(ws, "se", "=SQRT(G{r}/E{r}+D{r}/B{r})", n, NUM4)
    add_formula_column(ws, "ci_low", "=H{r}-about!$B$6*I{r}", n, NUM)
    add_formula_column(ws, "ci_high", "=H{r}+about!$B$6*I{r}", n, NUM)
    add_formula_column(ws, "rel_diff", "=H{r}/C{r}", n, PCT)
    add_formula_column(ws, "p_value", "=2*(1-NORM.S.DIST(ABS(H{r}/I{r}),TRUE))", n, NUM4)
    add_formula_column(ws, "significant", "=IF(M{r}<about!$B$4,\"yes\",\"no\")", n)

    pw = wb.create_sheet("power")
    p = findings["promo"]["power"]
    pw.append(["input", "value"])
    style_header(pw, 1, 2)
    for row in [["sd_contribution (control)", p["sd_contribution"]], ["n_per_arm", p["n_per_arm"]],
                ["control_mean", p["control_mean"]], ["cuped_variance_reduction", p["variance_reduction"]]]:
        pw.append(row)
    for r in range(2, 6):
        pw[f"B{r}"].fill = INPUT_FILL
    pw.append([])
    pw.append(["output", "formula"])
    style_header(pw, 7, 2)
    pw.append(["mde_abs", "=(about!$B$6+about!$B$7)*B2*SQRT(2/B3)"])
    pw.append(["mde_rel", "=B8/B4"])
    pw.append(["mde_abs_cuped", "=B8*SQRT(1-B5)"])
    pw.append(["mde_rel_cuped", "=B10/B4"])
    pw.append(["n_per_arm_for_1pct_lift_cuped", "=((about!$B$6+about!$B$7)*B2*SQRT(1-B5)/(0.01*B4))^2*2"])
    for r, f in [(9, PCT), (11, PCT), (8, NUM), (10, NUM), (12, "#,##0")]:
        pw[f"B{r}"].number_format = f
    autosize(pw)

    daily = con.execute("SELECT * FROM dq_assignment_daily ORDER BY assign_date").df()
    sd = wb.create_sheet("srm_daily")
    write_frame(sd, daily, {"assign_date": "yyyy-mm-dd"})
    m = len(daily)
    add_formula_column(sd, "expected_each", "=(B{r}+C{r})/2", m, "#,##0.0")
    add_formula_column(sd, "chi_square", "=(B{r}-D{r})^2/D{r}+(C{r}-D{r})^2/D{r}", m, NUM)
    add_formula_column(sd, "p_value", "=CHISQ.DIST.RT(E{r},1)", m, "0.000000")
    add_formula_column(sd, "flagged", f"=IF(F{{r}}<about!$B$8/{m},\"SRM\",\"ok\")", m)
    sd.conditional_formatting.add(f"G2:G{m + 1}", FormulaRule(formula=['G2="SRM"'], fill=PatternFill("solid", fgColor="F8D7D7")))

    two = con.execute("PIVOT pilot_2x2 ON pilot_group || '_' || period USING first(value) GROUP BY metric ORDER BY metric").df()
    two = two[["metric", "treatment_before", "treatment_after", "control_before", "control_after"]]
    pt = wb.create_sheet("pilot_2x2")
    write_frame(pt, two, {c: NUM4 for c in two.columns if c != "metric"})
    add_formula_column(pt, "raw_did", "=(C{r}-B{r})-(E{r}-D{r})", len(two), NUM4)
    add_formula_column(pt, "raw_did_rel_to_treated_before", "=F{r}/B{r}", len(two), PCT)
    pt.cell(row=len(two) + 3, column=1, value="Raw 2x2 on order-weighted group means; the README's estimate adds node and date fixed effects and clustered errors.")
    out.parent.mkdir(exist_ok=True)
    wb.save(out)
    return out
