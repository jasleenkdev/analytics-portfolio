"""Excel workbook: ABC-XYZ classification and the perishable wastage model as live formulas."""
from __future__ import annotations

from pathlib import Path

from openpyxl import Workbook
from openpyxl.formatting.rule import FormulaRule
from openpyxl.styles import Font, PatternFill

from shared.excel import INPUT_FILL, add_formula_column, autosize, style_header, write_frame

MONEY, PCT, NUM2 = "#,##0.00", "0.0%", "0.00"


def build(con, cfg: dict, out: Path) -> Path:
    a, s = cfg["analysis"], cfg["assortment"]
    wb = Workbook()
    ab = wb.active
    ab.title = "about"
    ab.append(["Assortment and wastage workbook (SIMULATED DATA: generated by a seeded Python model, not real company data)"])
    ab["A1"].font = Font(bold=True, size=13)
    ab.append([])
    ab.append(["Parameter", "Value", "Meaning"])
    style_header(ab, 3, 3)
    params = [("abc_a_share", a["abc_a_share"], "Cumulative revenue share closing class A"),
              ("abc_b_share", a["abc_b_share"], "Cumulative revenue share closing class B"),
              ("xyz_x_cv", a["xyz_x_cv"], "Weekly demand CV closing class X"),
              ("xyz_y_cv", a["xyz_y_cv"], "Weekly demand CV closing class Y"),
              ("wastage_risk_threshold", a["wastage_risk_threshold"], "Days of cover / shelf life at which waste is structural"),
              ("target_cover_share", a["target_cover_share"], "Recommended cover as a share of shelf life"),
              ("reduce_min_daily_units", s["reduce_min_daily_units"], "Minimum daily sales for a depth cut"),
              ("waste_saving_low", s["waste_saving_low"], "Share of waste cost saved by a depth cut (low)"),
              ("waste_saving_high", s["waste_saving_high"], "Share of waste cost saved by a depth cut (high)")]
    for p in params:
        ab.append(list(p))
    for r in range(4, 4 + len(params)):
        ab[f"B{r}"].fill = INPUT_FILL
    ab.append([])
    ab.append(["Edit the yellow cells: classes, risk flags, recommended stock levels and savings recompute. Facts (revenue, CV, "
               "stock, sales, waste) are exported values from the SQL layer."])
    autosize(ab)
    ab.column_dimensions["C"].width = 70
    P = {name: f"about!$B${i}" for i, (name, _, _) in enumerate(params, start=4)}

    x = con.execute("""SELECT sku_id, category, revenue, gross_margin, weekly_cv, ranged_nodes, units_per_ranged_node_week
                       FROM abc_xyz ORDER BY revenue DESC, sku_id""").df()
    ws = wb.create_sheet("abc_xyz")
    write_frame(ws, x, {"revenue": MONEY, "gross_margin": MONEY, "weekly_cv": NUM2, "units_per_ranged_node_week": NUM2})
    n, last = len(x), len(x) + 1
    add_formula_column(ws, "revenue_share", f"=C{{r}}/SUM($C$2:$C${last})", n, "0.00%")
    add_formula_column(ws, "cum_share", f"=SUM($C$2:C{{r}})/SUM($C$2:$C${last})", n, PCT)
    add_formula_column(ws, "abc", f"=IF(I{{r}}-H{{r}}<{P['abc_a_share']},\"A\",IF(I{{r}}-H{{r}}<{P['abc_b_share']},\"B\",\"C\"))", n)
    add_formula_column(ws, "xyz", f"=IF(E{{r}}<={P['xyz_x_cv']},\"X\",IF(E{{r}}<={P['xyz_y_cv']},\"Y\",\"Z\"))", n)
    add_formula_column(ws, "class", "=J{r}&K{r}", n)
    add_formula_column(ws, "margin_rate", "=D{r}/C{r}", n, PCT)

    mx = wb.create_sheet("abc_xyz_matrix", 1)
    mx.append(["SKU count", "X", "Y", "Z", "revenue share X", "revenue share Y", "revenue share Z"])
    style_header(mx, 1, 7)
    for i, cls in enumerate("ABC", start=2):
        row = [cls] + [f"=COUNTIFS(abc_xyz!$J:$J,\"{cls}\",abc_xyz!$K:$K,\"{z}\")" for z in "XYZ"]
        row += [f"=SUMIFS(abc_xyz!$C:$C,abc_xyz!$J:$J,\"{cls}\",abc_xyz!$K:$K,\"{z}\")/SUM(abc_xyz!$C:$C)" for z in "XYZ"]
        mx.append(row)
        for c in "EFG":
            mx[f"{c}{i}"].number_format = PCT
    autosize(mx)

    w = con.execute("""SELECT node_id, sku_id, category, shelf_life_days, avg_opening_stock, avg_daily_sold,
                       units_received, units_wasted, unit_cost FROM wastage_node_sku ORDER BY waste_cost DESC""").df()
    ww = wb.create_sheet("wastage_model")
    write_frame(ww, w, {"avg_opening_stock": NUM2, "avg_daily_sold": NUM2, "unit_cost": MONEY})
    m = len(w)
    add_formula_column(ww, "days_of_cover", "=IFERROR(E{r}/F{r},\"\")", m, NUM2)
    add_formula_column(ww, "risk_score", "=IFERROR(J{r}/D{r},\"\")", m, NUM2)
    add_formula_column(ww, "risk_flag", f"=IF(AND(ISNUMBER(K{{r}}),K{{r}}>={P['wastage_risk_threshold']}),\"high\",\"ok\")", m)
    add_formula_column(ww, "waste_rate", "=IFERROR(H{r}/G{r},0)", m, PCT)
    add_formula_column(ww, "waste_cost", "=H{r}*I{r}", m, MONEY)
    add_formula_column(ww, "target_cover_days", f"={P['target_cover_share']}*D{{r}}", m, NUM2)
    add_formula_column(ww, "recommended_stock_units", "=ROUNDUP(O{r}*F{r},0)", m, "#,##0")
    add_formula_column(ww, "cut_depth", f"=IF(AND(L{{r}}=\"high\",F{{r}}>={P['reduce_min_daily_units']}),\"yes\",\"no\")", m)
    add_formula_column(ww, "saving_low", f"=IF(Q{{r}}=\"yes\",N{{r}}*{P['waste_saving_low']},0)", m, MONEY)
    add_formula_column(ww, "saving_high", f"=IF(Q{{r}}=\"yes\",N{{r}}*{P['waste_saving_high']},0)", m, MONEY)
    ww.conditional_formatting.add(f"L2:L{m + 1}", FormulaRule(formula=['L2="high"'], fill=PatternFill("solid", fgColor="F8D7D7")))
    tot = m + 3
    ww.cell(row=tot, column=1, value="Total depth-cut saving (low / high)").font = Font(bold=True)
    ww.cell(row=tot, column=18, value=f"=SUM(R2:R{m + 1})").number_format = MONEY
    ww.cell(row=tot, column=19, value=f"=SUM(S2:S{m + 1})").number_format = MONEY
    out.parent.mkdir(exist_ok=True)
    wb.save(out)
    return out
